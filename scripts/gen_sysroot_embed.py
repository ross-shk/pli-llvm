"""scripts/gen_sysroot_embed.py — embed a link sysroot as C++ byte arrays.

Single-binary distribution (ADR-227): release archives contain only
pli(.exe), so the vendored link inputs (musl objects, mingw import libs,
macOS .tbd stubs) are compiled into the driver like the runtime bitcode
(scripts/gen_embed.py is single-blob; this script handles a multi-file
sysroot with relative paths). At link time the driver materializes the
blobs to a temp dir (src/hostcrt.cpp).

Usage:
  gen_sysroot_embed.py <srcdir> <outdir> <array_prefix> <manifest.inc>
      <set_name> <target_keys> [<relpath> ...]
  Each <srcdir>/<relpath> becomes <outdir>/<sanitized>.cpp holding one
  `extern "C"` byte array; <manifest.inc> declares them and defines the
  kEmbeddedSysrootFiles table {(path, data, len)} plus kEmbeddedSysrootName
  (<set_name>: "musl", "mingw", or "sdk" — which link path the set feeds) and
  kEmbeddedSysrootTargetKeys (the ABI families the set serves, comma
  separated — ADR-234: a cross link may use the set only for a listed key).
  With no <relpath>s the manifest holds an empty table (arch mismatch /
  missing sources at build time: the driver falls back to the host
  toolchain).
  Sanitized: every non-alphanumeric run becomes '_' (so
  libpli_builtins-x86_64.a and usr/lib/libSystem.tbd are valid identifiers).
  Zero-length files emit the 1-dummy-byte form (MSVC rejects zero-size
  arrays; the _len stays 0 so the byte is never read).
"""
import os
import re
import sys


def sanitize(relpath: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "_", relpath).strip("_")


def emit_array(f, array_name: str, data: bytes) -> None:
    if len(data) == 0:
        f.write(f'extern "C" const unsigned char {array_name}[1] = {{\n')
        f.write("  0x00,\n")
    else:
        f.write(f'extern "C" const unsigned char {array_name}[] = {{\n')
        for i in range(0, len(data), 16):
            row = ", ".join(f"0x{b:02x}" for b in data[i : i + 16])
            f.write("  " + row + ",\n")
    f.write("};\n")
    f.write(f"extern \"C\" const unsigned long {array_name}_len = {len(data)}UL;\n")


def main(srcdir: str, outdir: str, prefix: str, manifest: str,
         set_name: str, target_keys: str, relpaths) -> None:
    os.makedirs(outdir, exist_ok=True)
    entries = []
    for rel in relpaths:
        with open(os.path.join(srcdir, rel), "rb") as f:
            data = f.read()
        stem = sanitize(rel)
        array_name = f"{prefix}{stem}"
        with open(os.path.join(outdir, stem + ".cpp"), "w") as f:
            f.write(f"// {stem}.cpp (GENERATED by scripts/gen_sysroot_embed.py)\n")
            f.write(f"// Do not edit. Regenerated on every build from {rel}.\n")
            emit_array(f, array_name, data)
        entries.append((rel, array_name, len(data)))
    with open(manifest, "w") as f:
        f.write("// embedded_sysroot.inc (GENERATED by scripts/gen_sysroot_embed.py)\n")
        f.write("// Do not edit. Regenerated on every build from the sysroot sources.\n")
        for _, array_name, _ in entries:
            f.write(f"extern \"C\" const unsigned char {array_name}[];\n")
            f.write(f"extern \"C\" const unsigned long {array_name}_len;\n")
        f.write("static const pli::SysrootFile kEmbeddedSysrootFiles[] = {\n")
        for rel, array_name, _ in entries:
            f.write(f'  {{"{rel}", {array_name}, {array_name}_len}},\n')
        f.write("};\n")
        f.write("static const size_t kEmbeddedSysrootFileCount = "
                f"{len(entries)};\n")
        f.write(f'static const char kEmbeddedSysrootName[] = "{set_name}";\n')
        keys = [k.strip() for k in target_keys.split(",") if k.strip()]
        f.write("static const char* const kEmbeddedSysrootTargetKeys[] = {\n")
        for k in keys:
            f.write(f'  "{k}",\n')
        f.write("  nullptr,\n};\n")


if __name__ == "__main__":
    if len(sys.argv) < 7:
        print("Usage: gen_sysroot_embed.py <srcdir> <outdir> <array_prefix> "
              "<manifest.inc> <set_name> <target_keys> [<relpath> ...]",
              file=sys.stderr)
        sys.exit(1)
    main(sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5],
         sys.argv[6], sys.argv[7:])
