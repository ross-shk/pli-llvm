"""scripts/gen_embed.py — turn a runtime .bc into a C++ byte array.

Mirrors how gen_rules.py generates sources; python is already a build dep,
so no binutils (objcopy/sectcreate/rc.exe) is needed on any host.

Usage: gen_embed.py <input.bc> <output.inc> [array_base] [target_suffix]
  array_base: array name stem (default "pli_embedded_runtime_bc";
    the platform blob uses "pli_embedded_rtplat_bc")
  target_suffix: optional suffix for array names (e.g., "_linux_x86_64")
  (array_base comes first so CMake's empty-arg dropping can never shift the
  stem: the suffix is the only argument that may be empty, and only for the
  host blob, whose arrays carry no suffix.)
  If input is /dev/null, generates empty arrays (stub for non-cross builds).
"""
import os
import sys


def main(src: str, dst: str, array_base: str = "pli_embedded_runtime_bc",
         target_suffix: str = "") -> None:
    # "/dev/null" is a sentinel string here, never opened, so this stub path
    # is portable (Windows has no /dev/null file).
    if src == "/dev/null":
        # Generate empty stub arrays for non-cross builds
        data = b""
    else:
        with open(src, "rb") as f:
            data = f.read()
    with open(dst, "w") as f:
        f.write("// embedded_runtime.inc (GENERATED by scripts/gen_embed.py)\n")
        f.write(f"// Do not edit. Regenerated on every build from {os.path.basename(src)}.\n")
        array_name = f"{array_base}{target_suffix}"
        if len(data) == 0:
            # MSVC/cl.exe rejects zero-size arrays (C2466); emit one dummy
            # byte. clang-cl also rejects this; use 1-element arrays.
            # The _len stays 0 so the byte is never read.
            f.write(f'extern "C" const unsigned char {array_name}[1] = {{\n')
            f.write("  0x00,\n")
        else:
            f.write(f'extern "C" const unsigned char {array_name}[] = {{\n')
            for i in range(0, len(data), 16):
                row = ", ".join(f"0x{b:02x}" for b in data[i : i + 16])
                f.write("  " + row + ",\n")
        f.write("};\n")
        f.write(
            f'extern "C" const unsigned long {array_name}_len = '
            f"{len(data)}UL;\n"
        )


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("Usage: gen_embed.py <input.bc> <output.inc> [array_base] [target_suffix]",
              file=sys.stderr)
        sys.exit(1)
    array_base = sys.argv[3] if len(sys.argv) > 3 else "pli_embedded_runtime_bc"
    target_suffix = sys.argv[4] if len(sys.argv) > 4 else ""
    main(sys.argv[1], sys.argv[2], array_base, target_suffix)
